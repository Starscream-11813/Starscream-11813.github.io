"""Generate lightweight thumbnails for the Publications and Lit posts pages.

The images in images/ are full size (paper teasers run to several MB, one a
22 MB animated GIF; book covers to almost 800 KB), too heavy for a listing.
For every `teaser:` in _publications/, this writes a 560 px wide WebP to
images/publications/; an animated GIF also gets a silent, looping MP4 (made
with ffmpeg), with the WebP of its first frame as the poster. For every
`teaser:` in _posts/ (the book covers), it writes a 320 px wide WebP to
images/books/. Each thumbnail's size goes to _data/publication_thumbnails.yml
or _data/book_covers.yml, so the page reserves the image's full height before
it loads. The originals stay where they are; the Publications page still shows
them full size on request. Run from the repository root after adding or
changing a teaser or cover (needs Pillow, and ffmpeg for animated teasers):

    python scripts/thumbnails.py

Until it is run, a new card simply shows its original image.
"""
import re
import shutil
import subprocess
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent

# Each set: the pages that name the images, where the thumbnails go, the file
# that records their sizes, their width, and what to call one in messages.
SETS = [
    ('_publications', 'images/publications', '_data/publication_thumbnails.yml', 560, 'teaser'),
    ('_posts', 'images/books', '_data/book_covers.yml', 320, 'cover'),
]


def teasers(folder):
    for page in sorted((ROOT / folder).glob('*.md')):
        match = re.search(r'^teaser:\s*["\']?([^"\'\n]+?)["\']?\s*$', page.read_text(encoding='utf-8'), re.M)
        if match:
            yield ROOT / 'images' / match.group(1).strip()


def flatten(image):
    """Figures and covers read best on white, in either site theme."""
    image = image.convert('RGBA')
    canvas = Image.new('RGB', image.size, 'white')
    canvas.paste(image, mask=image.getchannel('A'))
    return canvas


def save_webp(image, target, width):
    if image.width > width:
        image = image.resize((width, round(image.height * width / image.width)), Image.LANCZOS)
    flatten(image).save(target, 'WEBP', quality=80, method=6)


def save_mp4(source, target, width):
    ffmpeg = shutil.which('ffmpeg')
    if not ffmpeg:
        print(f'  ffmpeg not found; {source.name} keeps only a still thumbnail')
        return
    subprocess.run([ffmpeg, '-y', '-loglevel', 'error', '-i', str(source),
                    '-vf', f'scale={width}:-2:flags=lanczos,format=yuv420p',
                    '-c:v', 'libx264', '-preset', 'slow', '-crf', '27',
                    '-movflags', '+faststart', '-an', str(target)], check=True)


def make(pages, output, sizes_file, width, noun):
    output = ROOT / output
    output.mkdir(parents=True, exist_ok=True)
    sizes = {}
    for source in teasers(pages):
        if not source.exists():
            print(f'  missing {noun}: {source.relative_to(ROOT)}')
            continue
        still = output / f'{source.stem}.webp'
        if not still.exists() or still.stat().st_mtime < source.stat().st_mtime:
            with Image.open(source) as image:
                animated = getattr(image, 'is_animated', False)
                image.seek(0)
                save_webp(image.copy(), still, width)
            if animated:
                save_mp4(source, output / f'{source.stem}.mp4', width)
            print(f'  {source.name} -> {still.relative_to(ROOT).as_posix()}' + (' + .mp4' if animated else ''))
        with Image.open(still) as image:
            sizes[source.stem] = image.size
    lines = [f'# Generated by scripts/thumbnails.py: each {noun} thumbnail\'s width and',
             '# height, so the page can reserve its space before it loads.']
    lines += [f'{stem}: [{w}, {h}]' for stem, (w, h) in sorted(sizes.items(), key=lambda item: item[0].lower())]
    (ROOT / sizes_file).write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')


def main():
    for job in SETS:
        make(*job)


if __name__ == '__main__':
    main()
